const fs=require('node:fs');
const path=require('node:path');
const assert=require('node:assert/strict');
const candidates=process.env.PATH.split(path.delimiter).map(p=>path.resolve(p,'../playwright'));
const packageDir=candidates.find(p=>fs.existsSync(path.join(p,'package.json')));
if(!packageDir)throw new Error('Ejecutar con: npx --yes --package=playwright node scripts/review-ui.cjs');
const {chromium}=require(packageDir);
(async()=>{
 const browser=await chromium.launch({channel:'chrome',headless:true});
 const errors=[],results=[];
 const page=await browser.newPage({viewport:{width:1440,height:1000},deviceScaleFactor:1});
 page.on('pageerror',error=>errors.push(error.message));
 const dir=path.resolve('docs/screenshots');fs.mkdirSync(dir,{recursive:true});
 const shot=async name=>{await page.screenshot({path:path.join(dir,name+'.png'),fullPage:(await page.getByRole('dialog').count())===0});};
 const noOverflow=async()=>page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth+1);
 try{
  await page.goto('http://localhost:5000');
  await page.getByRole('heading',{name:'Inicia sesión',exact:true}).waitFor();
  await shot('01-acceso');
  await page.getByRole('button',{name:'Ingresar al sistema'}).click();
  await page.locator('.analytics-dashboard').waitFor();
  await shot('02-panel-general');
  await page.getByRole('button',{name:'Gráfico de líneas',exact:true}).click();
  assert.equal(await page.getByRole('button',{name:'Gráfico de líneas',exact:true}).getAttribute('aria-pressed'),'true');
  assert.equal(await page.locator('.financial-plot polyline').count(),2);
  await shot('13-grafico-lineas');
  await page.getByRole('button',{name:'Gráfico de barras',exact:true}).click();
  assert((await page.locator('.financial-plot rect').count())>0);

  const routes=['employees','orgchart','cargos','schedules','periods','payroll','payments','remunerations','proposals','parameters','reports','audit','changes'];
  for(const route of routes){
   await page.goto(`http://localhost:5000/#${route}`);
   await page.locator(`[data-view="${route}"]`).waitFor();
   await page.locator('.loading-panel').waitFor({state:'hidden'});
   await page.waitForTimeout(350);
   assert(await noOverflow(),`Desbordamiento de página: ${route}`);
   assert.equal(await page.locator('.feedback.error').count(),0,`Error visible: ${route}`);
   results.push({route,theme:'light',overflow:false});
   await shot('03-'+route);
  }
  await page.goto('http://localhost:5000/#schedules');
  await page.getByRole('button',{name:'Nueva jornada',exact:true}).click();
  await page.getByLabel('Hora de entrada').fill('08:00');
  await page.getByLabel('Hora de salida').fill('17:00');
  await page.getByRole('button',{name:'Cancelar',exact:true}).click();
  await page.goto('http://localhost:5000/#employees');
  await page.locator('.people-table tbody tr').first().waitFor();
  await page.getByRole('button',{name:/Más filtros/}).click();
  await page.getByRole('spinbutton',{name:'Sueldo mínimo del filtro'}).fill('999999');
  await page.getByRole('heading',{name:'No encontramos colaboradores'}).waitFor();
  await page.getByRole('button',{name:'Limpiar filtros',exact:true}).click();
  const firstEmployee = await page.getByRole('button',{name:/Editar a /}).first().getAttribute('aria-label');
  await page.getByRole('textbox',{name:'Buscar colaborador'}).fill(firstEmployee.replace(/^Editar a /,''));
  assert.equal(await page.locator('.people-table tbody tr').count(),1);
  await page.getByRole('textbox',{name:'Buscar colaborador'}).fill('');
  await page.getByRole('combobox',{name:'Filtrar por departamento'}).selectOption({index:1});
  await shot('14-filtros-colaboradores');
  await page.getByRole('button',{name:'Limpiar filtros',exact:true}).click();
  await page.getByRole('button',{name:/Más filtros/}).click();
  await page.getByRole('button',{name:/Editar a /}).first().click();
  await page.getByRole('tab',{name:'Décimos',exact:true}).click();
  await page.getByRole('heading',{name:'¿Cómo recibe sus décimos?'}).waitFor();
  await shot('04-decimos');
  assert.equal(await page.getByRole('radio').count(),4);
  await page.getByRole('tab',{name:'Impuesto a la renta',exact:true}).click();
  await page.locator('.tax-monthly-result').waitFor();
  await shot('05-impuesto-renta');
  await page.getByRole('combobox',{name:'Mes de simulación de renta'}).selectOption('1');
  await page.getByText('Enero: sin retención.',{exact:true}).waitFor();
  assert.equal(await page.locator('.tax-monthly-result>strong').innerText(),'$0.00');
  await page.getByRole('combobox',{name:'Mes de simulación de renta'}).selectOption('2');
  await page.locator('.tax-expense-helper summary').click();
  await page.getByLabel('Gastos personales proyectados, sin IVA ni ICE ($)').fill('3000');
  await page.getByText('$540.00',{exact:true}).waitFor();
  await page.getByRole('button',{name:'Usar esta rebaja',exact:true}).click();
  assert.equal(await page.getByLabel('Rebaja por gastos personales ($ / año)').inputValue(),'540');
  // Cancel the form: the simulator never changes employee data or payrolls.

  await page.keyboard.press('Escape');
  await page.getByRole('dialog').waitFor({state:'hidden'});
  await page.goto('http://localhost:5000/#cargos');
  await page.locator('.salary-scale-catalog tbody tr').first().waitFor();
  assert.equal(await page.locator('.salary-scale-catalog tbody tr').count(),6);
  await shot('15-escalas-salariales');
  await page.getByRole('button',{name:'G6',exact:true}).click();
  assert((await page.getByRole('textbox',{name:'Buscar cargo'}).inputValue())==='G6');
  await page.getByRole('textbox',{name:'Buscar cargo'}).fill('');
  await page.getByRole('button',{name:/Editar cargo /}).first().click();
  await page.getByRole('dialog').waitFor();
  await shot('06-escala-salarial');
  await page.getByRole('button',{name:'Cancelar',exact:true}).click();
  await page.goto('http://localhost:5000/#payroll');
  await page.locator('.payroll-data-table tbody tr').first().waitFor();
  const firstPerson=await page.locator('.payroll-data-table tbody tr td strong').first().innerText();
  const nextPage=page.getByRole('button',{name:'Página siguiente',exact:true});
  if(await nextPage.isEnabled()){
    await nextPage.click();
    assert.notEqual(await page.locator('.payroll-data-table tbody tr td strong').first().innerText(),firstPerson);
    await page.getByRole('button',{name:'Página anterior',exact:true}).click();
  }
  await page.getByRole('textbox',{name:'Buscar en nómina'}).fill(firstPerson);
  assert.equal(await page.locator('.payroll-data-table tbody tr').count(),1);
  await page.getByRole('textbox',{name:'Buscar en nómina'}).fill('');
  await page.getByRole('button',{name:/Horas extra de /}).first().waitFor();
  await page.getByRole('button',{name:/Horas extra de /}).first().click();
  await page.getByRole('checkbox',{name:/Realizó horas extra/}).waitFor();
  await page.getByRole('checkbox',{name:/Realizó horas extra/}).check();
  await page.getByLabel('Horas con recargo del 50%').fill('8');
  await page.getByLabel('Horas con recargo del 100%').fill('2');
  await shot('11-horas-extra');
  await page.getByRole('button',{name:'Cancelar',exact:true}).click();
  await page.getByRole('button',{name:/Ver rol/i}).first().click();
  await page.locator('.payment-slip').waitFor();
  await shot('12-rol-individual');
  assert(await noOverflow(),'Desbordamiento del rol individual');
  results.push({route:'slip',theme:'light',overflow:false});
  await page.setViewportSize({width:390,height:844});
  assert(await noOverflow(),'Desbordamiento móvil del rol individual');
  await page.setViewportSize({width:1440,height:1000});
  await page.goto('http://localhost:5000/#orgchart');
  await page.locator('.position-card').first().waitFor();
  const expectedPositions=await page.evaluate(async()=>{
    const response=await fetch('/api/employees?status=ACTIVO',{headers:{Authorization:`Bearer ${localStorage.getItem('mysubs_token')}`}});
    const employees=await response.json();return [...new Set(employees.map(e=>e.position_id))].sort((a,b)=>a-b);
  });
  const shownPositions=await page.locator('.position-card').evaluateAll(nodes=>nodes.map(n=>Number(n.dataset.positionId)).sort((a,b)=>a-b));
  assert.deepEqual(shownPositions,expectedPositions,'El organigrama debe incluir solo cargos ocupados');
  assert.equal(await page.locator('.vacancy-label').count(),0);
  await page.getByRole('button',{name:'Contraer',exact:true}).click();
  assert.equal(await page.locator('.position-children').count(),0);
  await page.getByRole('button',{name:'Expandir',exact:true}).click();
  await page.getByRole('textbox',{name:'Buscar en el organigrama'}).fill('SIN COINCIDENCIA 1234');
  await page.getByText('No hay coincidencias para esta búsqueda.').waitFor();
  await page.goto('http://localhost:5000/#dashboard');
  await page.locator('.analytics-dashboard').waitFor();
  await page.getByRole('button',{name:'Activar tema oscuro'}).click();
  assert.equal(await page.locator('html').getAttribute('data-theme'),'dark');
  await shot('07-tema-oscuro');
  await page.goto('http://localhost:5000/#changes');
  await page.locator('.guide-card').first().waitFor();
  assert.equal(await page.locator('.guide-card').count(),6);
  await page.locator('.guide-card').first().getByRole('button',{name:'Ver en el sistema'}).click();
  await page.locator('[data-view="orgchart"]').waitFor();
  await page.getByRole('button',{name:'Activar tema claro'}).click();
  await page.setViewportSize({width:390,height:844});
  for(const route of ['dashboard',...routes]){
   await page.goto(`http://localhost:5000/#${route}`);
   await page.locator(`[data-view="${route}"]`).waitFor();
   await page.locator('.loading-panel').waitFor({state:'hidden'});
   await page.waitForTimeout(200);
   assert(await noOverflow(),`Desbordamiento móvil: ${route}`);
   results.push({route,viewport:390,overflow:false});
  }
  await page.goto('http://localhost:5000/#dashboard');
  await page.locator('.analytics-dashboard').waitFor();
  await shot('08-movil');
  await page.getByRole('button',{name:'Abrir menú',exact:true}).click();
  assert.equal(await page.getByRole('button',{name:'Cerrar menú',exact:true}).last().getAttribute('aria-expanded'),'true');
  await shot('09-menu-movil');
  await page.getByRole('button',{name:'Colaboradores',exact:true}).click();
  await page.locator('.people-table').waitFor();
  await page.getByRole('button',{name:/Editar a /}).first().click();
  await page.getByRole('tab',{name:'Décimos',exact:true}).click();
  await shot('10-formulario-movil');
  await page.keyboard.press('Escape');
  assert.equal(errors.length,0,errors.join('\n'));
  fs.writeFileSync(path.join(dir,'verification.json'),JSON.stringify({checkedAt:new Date().toISOString(),businessDataModified:false,results,errors},null,2));
  console.log(`PASS: ${results.length} vistas verificadas, navegación y formularios; capturas en docs/screenshots. Sin modificar datos de personal ni nóminas.`);
 }finally{await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});
